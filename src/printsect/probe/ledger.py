"""The ledger: what each probe is for and what it showed, kept by its number.

`.printsect/probes.json` is the record; `.printsect/PROBES.md` is rewritten from it on
every save for people to read. Where a probe is comes from its mark in the source; the
line kept here is a hint for finding it, refreshed by verification.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any

from ..core.errors import PsectError
from ..core.fsutil import ensure_state_dir, write_atomic

LEDGER_VERSION = 1

ACTIVE = "active"  # in the source
REMOVED = "removed"  # taken out by printsect
MISSING = "missing"  # gone from the source some other way


@dataclass
class Probe:
    n: int
    file: str
    line_hint: int
    lines: list[str]
    group: str | None = None
    by: str = "ai"
    anchor: str = ""
    purpose: str = ""
    expect: str = ""
    status: str = ACTIVE
    added: str = ""
    function: str | None = None
    notes: list[str] = field(default_factory=list)
    results: list[dict[str, Any]] = field(default_factory=list)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Probe:
        known = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        return cls(**known)


class Ledger:
    def __init__(self, state_dir: Path) -> None:
        self.state_dir = state_dir
        self.path = state_dir / "probes.json"
        self.next = 1
        self.probes: dict[int, Probe] = {}
        if self.path.is_file():
            self._load()

    def _load(self) -> None:
        try:
            data = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise PsectError(f"cannot read {self.path}: {exc}") from exc
        self.next = int(data.get("next", 1))
        for item in data.get("probes", []):
            probe = Probe.from_dict(item)
            parts = PurePosixPath(probe.file).parts
            if not parts or PurePosixPath(probe.file).is_absolute() or ".." in parts \
                    or ":" in parts[0]:
                raise PsectError(f"{self.path}: probe #{probe.n} names a file outside "
                                 f"the project ({probe.file!r}); fix or remove the record")
            self.probes[probe.n] = probe

    def take_number(self, seen_in_source: int = 0) -> int:
        """The next number, never one used before, nor one already in the source."""
        n = max(self.next, seen_in_source + 1, max(self.probes, default=0) + 1)
        self.next = n + 1
        return n

    def add(self, probe: Probe) -> None:
        self.probes[probe.n] = probe

    def active(self, group: str | None = None) -> list[Probe]:
        return [
            p
            for p in sorted(self.probes.values(), key=lambda p: p.n)
            if p.status == ACTIVE and (group is None or p.group == group)
        ]

    def files(self) -> set[str]:
        return {p.file for p in self.probes.values() if p.status != REMOVED}

    def save(self, marker_prefix: str) -> None:
        ensure_state_dir(self.state_dir)
        data = {
            "version": LEDGER_VERSION,
            "next": self.next,
            "probes": [asdict(p) for p in sorted(self.probes.values(), key=lambda p: p.n)],
        }
        write_atomic(self.path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
        write_atomic(self.state_dir / "PROBES.md", render_markdown(self, marker_prefix))


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def last_result(probe: Probe) -> str:
    if not probe.results:
        return ""
    r = probe.results[-1]
    hits = r.get("hits", 0)
    text = f"run {r.get('run', '?')}: {hits} hit" + ("" if hits == 1 else "s")
    values = r.get("values") or {}
    if values:
        shown = ", ".join(f"{k}" for k in list(values)[:3])
        text += f" ({shown})"
    if hits == 0:
        text += " - not reached"
    return text


def render_markdown(ledger: Ledger, prefix: str) -> str:
    rows = sorted(ledger.probes.values(), key=lambda p: p.n)
    active = [p for p in rows if p.status == ACTIVE]
    others = [p for p in rows if p.status != ACTIVE]
    out = [
        "# Probes",
        "",
        f"Generated by printsect from probes.json - do not edit. {len(active)} in the source.",
        f"Find one in the source by its mark, e.g. `{prefix}-AI:group #7`.",
        "",
    ]

    def table(items: list[Probe], title: str) -> None:
        out.extend([f"## {title}", ""])
        if not items:
            out.extend(["(none)", ""])
            return
        out.append("| # | Where | Function | Group | By | Purpose | Last result | Status |")
        out.append("|---|---|---|---|---|---|---|---|")
        for p in items:
            out.append(
                f"| {p.n} | {_cell(p.file)}:{p.line_hint} | {_cell(p.function or '')} "
                f"| {_cell(p.group or '')} | {p.by} | {_cell(p.purpose)} "
                f"| {_cell(last_result(p))} | {p.status} |"
            )
        out.append("")

    table(active, "In the source")
    table(others, "Taken out or missing")
    return "\n".join(out)
